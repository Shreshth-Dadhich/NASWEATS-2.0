import assert from 'node:assert/strict';
import fs from 'node:fs';
import {researchPackage} from '../../website/src/export.js';
import {analyze} from '../../website/src/analytics.js';
import {rectangle,weightedCells,regionalRecords} from '../../website/src/spatial.js';
const dataset=JSON.parse(fs.readFileSync('website/.generated/public/cache/gulf-temperature.json','utf8'));
const raw=fs.readFileSync('website/.generated/public/cache/raw/gulf-temperature.json','utf8');
dataset.originals=[{raw,sha256:dataset.source.raw_sha256,url:dataset.source.requested_url}];
delete dataset.source.raw_url;
const geometry=rectangle(dataset.bbox),records=regionalRecords(dataset,weightedCells(dataset,geometry),geometry),analysis=analyze(records,2001,2024);
const input={dataset,records,analysis,analysisB:analyze([],2001,2024),selection:{start:2001,end:2024},geometry};
const blob=await researchPackage(input),bytes=new Uint8Array(await blob.arrayBuffer()),text=new TextDecoder().decode(bytes);
assert.equal(new DataView(bytes.buffer).getUint32(0,true),0x04034b50);
const header=new DataView(bytes.buffer),firstOffset=30+header.getUint16(26,true)+header.getUint16(28,true),firstSize=header.getUint32(18,true);
assert.equal(new TextDecoder().decode(bytes.slice(firstOffset,firstOffset+firstSize)).trim().split('\r\n').length,2,'Single-region export must not contain an empty region B row.');
for(const name of ['monthly.csv','statistics.csv','selection.json','citation.txt','nasa-original-a-tile-1.json'])assert.ok(text.includes(name));
assert.ok(text.includes(raw));
dataset.originals[0].raw+=' ';
await assert.rejects(researchPackage(input),/integrity mismatch/);
console.log('PASS: live-tile research ZIP preserves original NASA bytes, citations, CSV and selection; modified source bytes prevent export.');
